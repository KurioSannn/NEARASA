<?php

namespace App\Services;

use Illuminate\Http\UploadedFile;
use Illuminate\Support\Facades\Storage;
use RuntimeException;

class MerchantPhotos
{
    public static function rules(): array
    {
        return ['nullable', 'image', 'mimes:jpg,jpeg,png,webp', 'max:2048', 'dimensions:max_width=6000,max_height=6000'];
    }

    public function store(UploadedFile $file): string
    {
        $path = $file->store('merchant', 'public');
        if (! $path) {
            throw new RuntimeException('Foto belum dapat disimpan.');
        }

        return '/media/'.basename($path);
    }

    public function delete(?string $url): void
    {
        // Only files generated by this uploader can be removed; seed assets stay intact.
        if ($url && preg_match('#^/media/([a-zA-Z0-9]{40}\.(?:jpg|jpeg|png|webp|pdf))$#D', $url, $match)) {
            Storage::disk('public')->delete('merchant/'.$match[1]);
        }
    }
}
